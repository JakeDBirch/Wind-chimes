#!/usr/bin/env python3
"""Distil the reference tube model into a table the phone's voice can play.

For a grid of pitches (half-octave steps across the app's range) and clapper
speeds, strike the 1-inch aluminium tube with the wooden clapper and with a
neighbouring tube, and record every mode's frequency ratio to the fundamental, its
damping ratio and its pressure amplitude at each speed. The voice interpolates in
log pitch and log speed between grid points.

    python3 modal_table.py --swift ../../ios/App/App/ChimeModalTable.swift
"""
import argparse
import math
import os
import sys
from types import SimpleNamespace

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from chime_model import Tube, clapper_modes, collide, mode_amplitude, tube_modes  # noqa: E402

PITCHES = [110 * 2 ** (i / 2) for i in range(13)]        # A2 … A7, half-octave steps
SPEEDS = [0.03, 0.06, 0.12, 0.25, 0.5, 1.0, 2.0]         # m/s, log spaced
F_MAX = 16000.0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--swift', required=True, help='Swift file to write')
    args = ap.parse_args()

    a = SimpleNamespace(strike=0.62, cord=0.224, clapper_mass=0.04, clapper_E=2e9, clapper_radius=0.035,
                        restitution=0.7, zeta_440=3.1e-4, zeta_slope=0.37, zeta_cord=2e-4, zeta_shell=2e-3,
                        f_max=F_MAX, air=0.0, zeta_air=0.012)
    nu_c = 0.3
    tables = {'wood': [], 'tube': []}
    for f1 in PITCHES:
        tube = Tube(f1)
        # A neighbour a fifth of an octave up, meeting at the same depth below the ring
        other = Tube(f1 * 2 ** 0.2)
        depth = (a.strike - a.cord) * tube.L
        other_frac = min(0.95, max(0.05, a.cord + depth / other.L))
        for striker in ('wood', 'tube'):
            if striker == 'wood':
                E_star = 1 / ((1 - nu_c ** 2) / a.clapper_E + (1 - tube.nu ** 2) / tube.E)
                k = 4 / 3 * E_star * math.sqrt(math.sqrt(a.clapper_radius * tube.Ro))
            else:
                E_star = tube.E / (2 * (1 - tube.nu ** 2))
                k = 4 / 3 * E_star * math.sqrt(math.sqrt(tube.Ro * other.Ro))
            rows = None
            for v in SPEEDS:
                target = tube_modes(tube, a.strike, a.cord, a)
                stk = clapper_modes(a.clapper_mass) if striker == 'wood' else tube_modes(other, other_frac, a.cord, a)
                collide(stk, target, v, k, a.restitution)
                sounding = [m for m in target if m.w > 0]
                if rows is None:
                    rows = [{'ratio': m.f / f1, 'zeta': m.zeta, 'shell': m.kind == 'shell', 'amps': []} for m in sounding]
                for r, m in zip(rows, sounding):
                    r['amps'].append(mode_amplitude(m, tube.Ro))
            tables[striker].append(rows)
        loud = max(r['amps'][-1] for r in tables['wood'][-1])
        print(f'{f1:7.1f} Hz: L {tube.L * 100:5.1f} cm, {len(tables["wood"][-1])} modes, loudest at 2 m/s {20 * math.log10(loud):.0f} dB')

    def swift_rows(rows):
        out = []
        for r in rows:
            amps = ', '.join(f'{x:.4g}' for x in r['amps'])
            out.append(f'            Mode(ratio: {r["ratio"]:.5g}, zeta: {r["zeta"]:.4g}, shell: {"true" if r["shell"] else "false"}, amps: [{amps}]),')
        return '\n'.join(out)

    lines = ['// Generated by scripts/reference/modal_table.py from the reference tube model. Do not edit.',
             '//',
             '// A 1-inch, 1.5 mm-wall aluminium tube struck at 0.62 of its length by a 40 g wooden',
             '// clapper (wood) or by a neighbouring tube (tube), at each of `speeds` m/s, for each',
             '// of `pitches` Hz. Each mode: frequency as a ratio to the fundamental, damping ratio,',
             '// whether it is an ovalling mode of the wall, and its pressure amplitude per speed.',
             '',
             'enum ChimeModalTable {',
             f'    static let speeds: [Double] = [{", ".join(f"{v:g}" for v in SPEEDS)}]',
             f'    static let pitches: [Double] = [{", ".join(f"{p:.4f}" for p in PITCHES)}]',
             '',
             '    struct Mode {',
             '        let ratio: Double',
             '        let zeta: Double',
             '        let shell: Bool',
             '        let amps: [Double]',
             '    }',
             '']
    for striker in ('wood', 'tube'):
        lines.append(f'    static let {striker}: [[Mode]] = [')
        for rows in tables[striker]:
            lines.append('        [')
            lines.append(swift_rows(rows))
            lines.append('        ],')
        lines.append('    ]')
        lines.append('')
    lines.append('}')
    with open(args.swift, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', args.swift)


if __name__ == '__main__':
    main()
